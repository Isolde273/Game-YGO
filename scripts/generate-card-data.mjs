import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

// A static ES module also works in the portable application's file:// pages.
const sources = await Promise.all(
  ['cards', 'manifest'].map((name) =>
    fs.readFile(new URL(`../public/locr-catalog/${name}.json`, import.meta.url), 'utf8'),
  ),
);
const cards = JSON.parse(sources[0]);
const prints = JSON.parse(sources[1]).map((entry) => {
  const {
    id,
    cardId,
    rarity,
    style,
    edition,
    overframe,
    front,
    officialArtVariant,
    kind,
    mask,
    normal,
    accent,
    border,
    calibration,
    film,
  } = entry;
  return {
    id,
    cardId,
    rarity,
    style,
    edition,
    overframe,
    front,
    officialArtVariant,
    kind,
    mask,
    normal,
    accent,
    border,
    calibration,
    film,
  };
});
const digest = createHash('sha256').update(sources.join('\n')).digest('hex');
const output = `// Generated by scripts/generate-card-data.mjs; do not edit.\nexport const sourceDigest = ${JSON.stringify(digest)};\nexport const catalogCards = ${JSON.stringify(cards)};\nexport const catalogPrints = ${JSON.stringify(prints)};\n`;
const target = new URL('../src/generated/locr-card-data.js', import.meta.url);
for (const print of prints.filter((p) => p.rarity === 'GMR')) {
  const original = new URL(`../public/locr-catalog/${print.front}`, import.meta.url);
  const blank = new URL(
    `../public/locr-catalog/${print.front.replace('-front.jpg', '-blank.jpg')}`,
    import.meta.url,
  );
  // GMR source art already contains a long black rectangle. Recover its print
  // substrate from the matching overframe art before drawing the shorter plaque.
  const matching = prints.find((p) => p.cardId === print.cardId && p.style === 'UR-OF');
  if (!matching) throw new Error(`Missing matching overframe art for ${print.id}`);
  const donor = new URL(`../public/locr-catalog/${matching.front}`, import.meta.url);
  const { data: substrate, info } = await sharp(await fs.readFile(donor))
    .extract({ left: 29, top: 812, width: 160, height: 30 })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  // Erase the ordinary card's password using the quiet strip above/below it.
  for (let y = 8; y < 28; y++)
    for (let x = 0; x < 160; x++)
      for (let c = 0; c < info.channels; c++) {
        const at = (row) => substrate[(row * 160 + x) * info.channels + c];
        const top = (at(6) + at(7)) / 2;
        const bottom = (at(28) + at(29)) / 2;
        const t = (y - 8) / 19;
        substrate[(y * 160 + x) * info.channels + c] = Math.round(top * (1 - t) + bottom * t);
      }
  const restored = await sharp(substrate, {
    raw: { width: 160, height: 30, channels: info.channels },
  })
    .extract({ left: 0, top: 0, width: 160, height: 28 })
    .png()
    .toBuffer();
  const overlay = Buffer.from(
    '<svg width="590" height="860"><polygon points="29,812 121,812 129,840 29,840" fill="#08090b"/></svg>',
  );
  const expected = await sharp(await fs.readFile(original))
    .composite([{ input: restored, left: 29, top: 812 }, { input: overlay }])
    .jpeg({ quality: 94, chromaSubsampling: '4:4:4' })
    .toBuffer();
  if (process.argv.includes('--check')) {
    if (!(await fs.readFile(blank)).equals(expected)) throw new Error('GMR neutral image is stale');
  } else await fs.writeFile(blank, expected);
}
if (process.argv.includes('--check')) {
  if ((await fs.readFile(target, 'utf8')) !== output)
    throw new Error('Card data is stale; run npm run cards:generate');
  console.log(`Card data matches catalog: ${cards.length} cards, ${prints.length} prints.`);
} else {
  await fs.writeFile(target, output);
  console.log(`Generated card data: ${cards.length} cards, ${prints.length} prints.`);
}

const bonusSources = await Promise.all(
  ['cards', 'manifest'].map((name) =>
    fs.readFile(new URL(`../public/vol2-catalog/${name}.json`, import.meta.url), 'utf8'),
  ),
);
const bonusCards = JSON.parse(bonusSources[0]);
const bonusPrints = JSON.parse(bonusSources[1]);
const bonusOutput = `// Generated by scripts/generate-card-data.mjs; do not edit.\nexport const bonusCards = ${JSON.stringify(bonusCards)};\nexport const bonusPrints = ${JSON.stringify(bonusPrints)};\n`;
const bonusTarget = new URL('../src/generated/vol2-card-data.js', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await fs.readFile(bonusTarget, 'utf8')) !== bonusOutput)
    throw new Error('vol.2 data is stale');
} else await fs.writeFile(bonusTarget, bonusOutput);
