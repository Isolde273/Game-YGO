import fs from 'node:fs/promises';
import path from 'node:path';
import { CARD_PRINTS } from '../src/game/card-data.js';
import { isMoney } from '../src/game/money.js';

function parseCSV(text) {
  const rows = [];
  let row = [],
    field = '',
    quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (char === '"') {
      if (quoted && text[i + 1] === '"') {
        field += '"';
        i++;
      } else quoted = !quoted;
    } else if (char === ',' && !quoted) {
      row.push(field);
      field = '';
    } else if ((char === '\n' || char === '\r') && !quoted) {
      if (char === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      if (row.some((value) => value.trim())) rows.push(row);
      row = [];
      field = '';
    } else field += char;
  }
  if (quoted) throw new Error('CSV引号未闭合');
  row.push(field);
  if (row.some((value) => value.trim())) rows.push(row);
  const headers = rows.shift()?.map((value) => value.replace(/^\uFEFF/, '').trim());
  if (!headers?.includes('printId') || !headers.includes('jihuanshePrice'))
    throw new Error('CSV需要printId和jihuanshePrice列');
  return rows.map((values) =>
    Object.fromEntries(headers.map((key, index) => [key, values[index]?.trim() ?? ''])),
  );
}

const input = process.argv[2];
if (!input) throw new Error('用法：node scripts/import-card-prices.mjs 价格CSV路径 [--check]');
const userPrices = process.argv.includes('--source=user');
const excludeZero = process.argv.includes('--exclude-zero');
if (excludeZero && !userPrices) throw new Error('零元排除仅适用于明确指定的用户售价表');
const source = userPrices ? '用户定价' : '集换社';
const inputPath = path.resolve(input);
const rows = parseCSV(await fs.readFile(inputPath, 'utf8'));
const prints = new Map(CARD_PRINTS.map((print) => [print.id, print]));
const seen = new Set(),
  entries = {},
  excludedPrintIds = [];
for (const row of rows) {
  const print = prints.get(row.printId);
  if (!print) throw new Error(`未知卡牌规格：${row.printId}`);
  if (seen.has(row.printId)) throw new Error(`重复卡牌规格：${row.printId}`);
  seen.add(row.printId);
  for (const key of ['cardId', 'rarity', 'style'])
    if (row[key] && row[key] !== String(print[key]))
      throw new Error(`${row.printId}的${key}不匹配`);
  if (row.overframe && row.overframe !== String(Boolean(print.overframe)))
    throw new Error(`${row.printId}的超框版本不匹配`);
  if (!row.jihuanshePrice) continue;
  if (!/^\d+(?:\.\d+)?$/.test(row.jihuanshePrice))
    throw new Error(`${row.printId}的集换价格式不正确`);
  const price = Number(row.jihuanshePrice);
  if (!isMoney(price) || (price === 0 && !excludeZero))
    throw new Error(`${row.printId}的价格不正确`);
  if (row.checkedAt && !Number.isFinite(Date.parse(row.checkedAt)))
    throw new Error(`${row.printId}的核对时间不正确`);
  if (price === 0) {
    excludedPrintIds.push(row.printId);
    continue;
  }
  entries[row.printId] = {
    price,
    sourceUrl: row.sourceUrl || inputPath,
    checkedAt: row.checkedAt || null,
  };
}
const excluded = new Set(excludedPrintIds);
const missing = CARD_PRINTS.filter(
  (print) => !Object.hasOwn(entries, print.id) && !excluded.has(print.id),
).map((print) => print.id);
const report = {
  source,
  input: inputPath,
  importedAt: new Date().toISOString(),
  total: CARD_PRINTS.length,
  required: CARD_PRINTS.length - excludedPrintIds.length,
  matched: Object.keys(entries).length,
  complete: missing.length === 0,
  missing,
  excludedPrintIds,
  entries,
};
const reportPath = path.join(path.dirname(inputPath), 'price-import-report.json');
await fs.writeFile(reportPath, JSON.stringify(report, null, 2));
console.log(
  `${source}核对：${report.matched}/${report.required}，排除${excludedPrintIds.length}个规格，缺少${missing.length}个规格。`,
);
if (missing.length) process.exitCode = 1;
else if (!process.argv.includes('--check')) {
  const target = path.resolve('src/generated/jihuanshe-prices.js');
  await fs.writeFile(
    target,
    `// Generated by scripts/import-card-prices.mjs.\nexport const jihuanshePrices = ${JSON.stringify({ source: report.source, importedAt: report.importedAt, excludedPrintIds, entries }, null, 2)};\n`,
  );
  console.log(`价格数据已生成：${target}`);
}
